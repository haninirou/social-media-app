package com.example.questionapp.security;

import io.jsonwebtoken.*;
import io.jsonwebtoken.SignatureAlgorithm;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.security.core.Authentication;
import org.springframework.stereotype.Component;
import io.jsonwebtoken.Claims;
import io.jsonwebtoken.ExpiredJwtException;
import io.jsonwebtoken.Jwts;
import io.jsonwebtoken.MalformedJwtException;
import io.jsonwebtoken.SignatureException;
import io.jsonwebtoken.UnsupportedJwtException;

import java.util.Date;

/**
 * JWT token provider - responsible for generating, validating and parsing JWT tokens
 * Creates a unique JWT token for each user at login
 */
@Component
public class JWTTokenProvider {

    @Value("${question.app.secret}")  // Value from application.properties
    private String APP_SECRET = "socialMedia";

    @Value("${question.expires.in}")  // Token validity period in milliseconds
    private long EXPIRES_IN;

    /**
     * Generates a JWT token based on the authentication
     * @param auth The authentication object with user information
     * @return The generated JWT token as a String
     */
    public String generateJWTToken(Authentication auth){
        // The principal contains the information of the logged-in user
        JWTUserDetails userDetails = (JWTUserDetails) auth.getPrincipal();
        // Calculate the token expiry time (current time + validity period)
        Date expireDate = new Date(new Date().getTime() + EXPIRES_IN);
        // Create the JWT token with user ID, issue time, expiry time and signature
        return Jwts.builder().setSubject(Long.toString(userDetails.getId()))
                .setIssuedAt(new Date()).setExpiration(expireDate)
                .signWith(SignatureAlgorithm.HS256, APP_SECRET).compact();
    }

    /**
     * Generates a JWT token based on the user ID (for refresh token)
     * @param userId The ID of the user
     * @return The generated JWT token as a String
     */
    public String generateJwtTokenByUserId(Long userId) {
        Date expireDate = new Date(new Date().getTime() + EXPIRES_IN);
        return Jwts.builder().setSubject(Long.toString(userId))
                .setIssuedAt(new Date()).setExpiration(expireDate)
                .signWith(SignatureAlgorithm.HS256, APP_SECRET).compact();
    }

    /**
     * Extracts the user ID from a JWT token
     * @param token The JWT token
     * @return The user ID as a Long
     */
    Long getUserIdFromJWT(String token){
        // Parse the token and extract the claims
        Claims claims = Jwts.parser().setSigningKey(APP_SECRET).parseClaimsJws(token).getBody();
        // Extract the subject (user ID) from the claims and convert it to Long
        return Long.parseLong(claims.getSubject());
    }

    /**
     * Validates a JWT token for validity and expiry time
     * @param token The JWT token to validate
     * @return true if the token is valid, false otherwise
     */
    boolean validateToken(String token) {
        try {
            // Parse the token - if successful, it is a token generated by us
            Jwts.parser().setSigningKey(APP_SECRET).parseClaimsJws(token);
            // Check that the token has not expired
            return !isTokenExpired(token);
        } catch (SignatureException e) {
            return false;  // Invalid signature
        } catch (MalformedJwtException e) {
            return false;  // Malformed token
        } catch (ExpiredJwtException e) {
            return false;  // Expired token
        } catch (UnsupportedJwtException e) {
            return false;  // Unsupported token type
        } catch (IllegalArgumentException e) {
            return false;  // Invalid arguments
        }
    }

    /**
     * Checks whether a token has expired
     * @param token The JWT token to check
     * @return true if the token has expired, false otherwise
     */
    private boolean isTokenExpired(String token) {
        // Extract the expiry time from the token
        Date expiration = Jwts.parser().setSigningKey(APP_SECRET).parseClaimsJws(token).getBody().getExpiration();
        // Check whether the expiry time is before the current time
        return expiration.before(new Date());
    }


}
